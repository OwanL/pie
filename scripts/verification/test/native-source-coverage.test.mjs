import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { collectSourceCoverage } from '../source-coverage.mjs';
import { assertCoverageQualification, buildNodeArgs, createNodeTestEntries, createTestEnvironment } from '../test-node.mjs';

const require = createRequire(import.meta.url);
const repo = fileURLToPath(new URL('../../../', import.meta.url));
const preload = fileURLToPath(new URL('../coverage-capture.cjs', import.meta.url));

// Qualification only: deliberately bypass the public refusal using the existing
// runner's fixture config, not a new execution or coverage implementation.
test('bounded native TS adapter matches retained AST accounting and rejects lost provenance', async t => {
  const temporary = mkdtempSync(path.join(os.tmpdir(), 'pie-native-coverage-qualification-'));
  const fixture = createTestEnvironment(process.env, { fixtureRoot: path.join(temporary, 'environment') });
  let qualified = false;
  t.after(() => {
    // Failed qualification retains raw V8, generated bytes, maps and config.
    if (qualified) rmSync(temporary, { recursive: true, force: true });
    else t.diagnostic(`Coverage qualification evidence retained: ${temporary}`);
  });
  const root = path.join(temporary, 'source');
  mkdirSync(root);
  const subject = path.join(root, 'subject.ts');
  const source = `export function classify(n: number) {
 if (n > 0) return 'positive';
 return n === 0 ? 'zero' : 'negative';
}
export function unused(n: boolean) { return n ? 1 : 2; }
`;
  writeFileSync(subject, source);
  const files = ['positive', 'zero'].map((name, index) => {
    const filename = path.join(root, `${name}.test.ts`);
    writeFileSync(filename, `import {test} from 'node:test';\nimport assert from 'node:assert/strict';\nimport {classify} from './subject';\ntest('${name}',()=>assert.equal(classify(${index ? 0 : 1}), '${name}'));\n`);
    return filename;
  });
  assert.throws(() => assertCoverageQualification(files, ['--experimental-test-coverage']), /TypeScript native coverage unqualified/);
  const reports = {};
  let nativeOptions;
  for (const lane of ['retained', 'native']) {
    const directory = path.join(temporary, lane);
    mkdirSync(directory);
    const options = { directory, root, cwd: root, includes: ['subject.ts'] };
    const env = { ...fixture.env,
      NODE_OPTIONS: `--require=${JSON.stringify(preload)}`,
      PIE_TEST_COVERAGE_DIR: directory, PIE_TEST_COVERAGE_ROOT: root,
      PIE_TEST_COVERAGE_CWD: root, PIE_TEST_COVERAGE_INCLUDES: JSON.stringify(options.includes),
      NODE_V8_COVERAGE: path.join(directory, 'v8'),
    };
    let args;
    if (lane === 'native') {
      const entries = createNodeTestEntries(files, path.join(temporary, 'entries'));
      const config = path.join(temporary, 'runner.json');
      writeFileSync(config, JSON.stringify({ ...entries, cwd: root, options: { coverage: true, concurrency: 1 },
        reporterNames: [], reporterDestinations: [], waitForOwnership: false }));
      args = buildNodeArgs(config, ['--experimental-test-coverage'], 1)
        .map(arg => arg === 'tsx' ? pathToFileURL(require.resolve('tsx')).href : arg);
      nativeOptions = options;
    } else {
      args = [require.resolve('tsx/cli'), '--test', '--test-concurrency=1', '--experimental-test-coverage', ...files];
    }
    const result = spawnSync(process.execPath, args, { cwd: repo, env, encoding: 'utf8', timeout: 30_000 });
    writeFileSync(path.join(directory, 'run.txt'), `${result.stdout}\n${result.stderr}`);
    assert.equal(result.error, undefined);
    assert.equal(result.status, 0, result.stderr + result.stdout);
    const captures = readdirSync(directory).filter(name => name.startsWith('scripts-'))
      .flatMap(name => JSON.parse(readFileSync(path.join(directory, name), 'utf8')).scripts);
    assert.ok(captures.length >= 2, 'both isolated test children capture the subject');
    for (const capture of captures) {
      assert.match(capture.sourceMapURL, /^data:.*base64,/);
      const map = JSON.parse(Buffer.from(capture.sourceMapURL.split('base64,')[1], 'base64'));
      assert.ok(map.sourcesContent.includes(source));
      assert.notEqual(capture.code, source);
    }
    reports[lane] = await collectSourceCoverage(options);
    assert.deepEqual(reports[lane].files.map(file => file.path), [subject], 'wrappers and test entries excluded');
  }
  assert.deepEqual(reports.native, reports.retained);
  const report = reports.native;
  assert.equal(report.totalBranchCount, 6);
  assert.equal(report.coveredBranchCount, 3);
  const untouched = report.files[0].branches.filter(branch => branch.locations.every(loc => loc.start.line === 5));
  assert.equal(untouched.length, 1);
  assert.deepEqual(untouched[0].counts, [0, 0], 'untouched branch arms stay zero');
  const names = readdirSync(nativeOptions.directory).filter(name => name.startsWith('scripts-'));
  const target = path.join(nativeOptions.directory, names[0]);
  const original = readFileSync(target, 'utf8');
  rmSync(target);
  await assert.rejects(collectSourceCoverage(nativeOptions), /Missing.*capture/i);
  writeFileSync(target, original);
  const record = JSON.parse(original);
  const map = JSON.parse(Buffer.from(record.scripts[0].sourceMapURL.split('base64,')[1], 'base64'));
  map.sourcesContent[0] += '\n// conflicting';
  record.scripts[0].sourceMapURL = `data:application/json;base64,${Buffer.from(JSON.stringify(map)).toString('base64')}`;
  writeFileSync(target, JSON.stringify(record));
  await assert.rejects(collectSourceCoverage(nativeOptions), /source map identity|Conflicting source/i);
  writeFileSync(target, original);
  assert.ok(readdirSync(path.join(nativeOptions.directory, 'v8')).length > 0, 'accounting failure does not delete raw evidence');
  qualified = true;
});
