#!/usr/bin/env node
// scripts/sync-models.mjs — regenerate pie's derived model-config files from models.yaml.
//
// Source of truth: models.yaml (repo root) + models.schema.json.
// Derived (generated): models.json, model-profiles.yaml, proxy/litellm_config.yaml,
// and the model fields of settings.json (read-modify-write merge).
//
// Usage:
//   node scripts/sync-models.mjs           # validate + regenerate (write changed files)
//   node scripts/sync-models.mjs --check   # dry-run: exit 1 if any derived file would change
//   node scripts/sync-models.mjs --verbose # print what changed per file
//
// `yaml` and `ajv` are resolved from extension/node_modules (no root deps needed),
// mirroring the lazy-resolve pattern in extensions/subagent/bucket-selector.ts.

import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';

// --- repo root (from this script's location, NOT cwd) -----------------------

/** Repo root derived from this module's URL (works regardless of cwd). */
export function repoRoot() {
  return path.resolve(fileURLToPath(import.meta.url), '..', '..');
}

// --- lazy dependency resolution (yaml + ajv from extension/node_modules) ----

function buildResolver() {
  const baseRequire = createRequire(import.meta.url);
  const candidates = [baseRequire];
  try {
    candidates.push(createRequire(new URL('../extension/package.json', import.meta.url)));
  } catch {
    // extension package not resolvable from this environment
  }
  return candidates;
}

function resolveDep(name) {
  for (const req of buildResolver()) {
    try {
      return req(name);
    } catch {
      // try next candidate
    }
  }
  throw new Error(
    `Could not resolve "${name}" — run "npm install" in extension/ (yaml is a direct dep, ajv is transitive).`,
  );
}

let _yaml;
function getYaml() {
  if (!_yaml) _yaml = resolveDep('yaml');
  return _yaml;
}

let _Ajv;
function getAjv() {
  if (!_Ajv) {
    const mod = resolveDep('ajv');
    _Ajv = mod.default || mod.Ajv;
  }
  return _Ajv;
}

